"""Build standalone SVG contours from OFL Noto Symbols fonts (requires fonttools).

Usage: python scripts/generate-celestial-symbols.py path/to/font-directory
The directory must contain NotoSansSymbols.ttf and NotoSansSymbols2-Regular.ttf.
"""
import json
import sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
symbols = instantiateVariableFont(TTFont(source / 'NotoSansSymbols.ttf'), {'wght': 500})
symbols2 = TTFont(source / 'NotoSansSymbols2-Regular.ttf')
codes = dict(zip(
    ['aries', 'taurus', 'gemini', 'cancer', 'leo', 'virgo', 'libra', 'scorpio',
     'sagittarius', 'capricorn', 'aquarius', 'pisces'], range(0x2648, 0x2654)))
codes.update(saturn=0x2644, jupiter=0x2643, mars=0x2642, sun_p=0x2609,
             venus=0x2640, mercury=0x263F, moon_p=0x263D,
             fire=0x1F702, water=0x1F704, air=0x1F701, earth=0x1F703)
paths = {}
for name, code in codes.items():
    font = symbols2 if name == 'sun_p' else symbols
    glyphs = font.getGlyphSet()
    glyph = glyphs[font.getBestCmap()[code]]
    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    scale = 48 / max(x1 - x0, y1 - y0)
    pen = SVGPathPen(glyphs, ntos=lambda n: f'{n:.3f}'.rstrip('0').rstrip('.') if n else '0')
    glyph.draw(TransformPen(pen, (scale, 0, 0, -scale,
        32 - (x0 + x1) * scale / 2, 32 + (y0 + y1) * scale / 2)))
    paths[name] = pen.getCommands()

module = '''// Generated by scripts/generate-celestial-symbols.py.
// Traditional Unicode glyphs from Noto Sans Symbols (500) and Noto Sans Symbols 2.
// Outlines retain their proportions; see public/assets/celestial/README.md and OFL licenses.
const paths = ''' + json.dumps(paths, ensure_ascii=False, indent=2) + ''';

export const celestialSymbolIds = Object.keys(paths);
export const celestialSymbolPath = (id) => paths[id] ? `/assets/celestial/${id}.svg` : null;
export function celestialSymbolSvg(id, color = '#fff') {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64" fill="${color}"><path d="${paths[id]}"/></svg>`;
}
'''
(root / 'src/data/celestialSymbols.js').write_text(module, encoding='utf-8')
for name, path in paths.items():
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64" fill="#fff"><path d="{path}"/></svg>\n'
    (root / f'public/assets/celestial/{name}.svg').write_text(svg, encoding='utf-8')
print(f'Generated {len(paths)} glyphs.')
